/* Console state */
static struct {
    uint32_t *fb;           /* Framebuffer pointer */
    uint32_t width;         /* Width in pixels */
    uint32_t height;        /* Height in pixels */
    uint32_t pitch;         /* Bytes per scanline */
    uint32_t cols;          /* Columns (characters) */
    uint32_t rows;          /* Rows (characters) */
    uint32_t cursor_x;      /* Cursor X (column) */
    uint32_t cursor_y;      /* Cursor Y (row) */
    uint32_t fg_color;      /* Foreground color */
    uint32_t bg_color;      /* Background color */
    bool initialized;
} console;

#define CHAR_WIDTH  8
#define CHAR_HEIGHT 16

/*
 * Draw a single pixel
 */
void fb_draw_pixel(uint32_t x, uint32_t y, uint32_t color) {
    if (x >= console.width || y >= console.height) return;
    uint32_t *pixel = (uint32_t*)((uint8_t*)console.fb + y * console.pitch + x * 4);
    *pixel = color;
}

/*
 * Fill a rectangle
 */
void fb_fill_rect(uint32_t x, uint32_t y, uint32_t w, uint32_t h, uint32_t color) {
    for (uint32_t py = y; py < y + h && py < console.height; py++) {
        uint32_t *row = (uint32_t*)((uint8_t*)console.fb + py * console.pitch);
        for (uint32_t px = x; px < x + w && px < console.width; px++) {
            row[px] = color;
        }
    }
}

/*
 * Draw a character at pixel position
 */
static void draw_char(uint32_t x, uint32_t y, char c, uint32_t fg, uint32_t bg) {
    const uint8_t *glyph = font_8x16[(uint8_t)c];

    for (int row = 0; row < CHAR_HEIGHT; row++) {
        uint32_t *pixel = (uint32_t*)((uint8_t*)console.fb + (y + row) * console.pitch + x * 4);
        uint8_t bits = glyph[row];

        for (int col = 0; col < CHAR_WIDTH; col++) {
            *pixel++ = (bits & 0x80) ? fg : bg;
            bits <<= 1;
        }
    }
}

/*
 * Scroll the console up by one line
 */
static void console_scroll(void) {
    /* Move all lines up by one character row */
    uint8_t *dst = (uint8_t*)console.fb;
    uint8_t *src = (uint8_t*)console.fb + CHAR_HEIGHT * console.pitch;
    uint32_t size = (console.rows - 1) * CHAR_HEIGHT * console.pitch;

    /* Copy memory */
    for (uint32_t i = 0; i < size; i++) {
        dst[i] = src[i];
    }

    /* Clear the last line */
    fb_fill_rect(0, (console.rows - 1) * CHAR_HEIGHT,
                 console.width, CHAR_HEIGHT, console.bg_color);
}

/*
 * Initialize the console
 */
void console_init(framebuffer_info_t *fb) {
    console.fb = (uint32_t*)(uintptr_t)fb->base;
    console.width = fb->width;
    console.height = fb->height;
    console.pitch = fb->pitch;
    console.cols = fb->width / CHAR_WIDTH;
    console.rows = fb->height / CHAR_HEIGHT;
    console.cursor_x = 0;
    console.cursor_y = 0;
    console.fg_color = DEFAULT_FG;
    console.bg_color = DEFAULT_BG;
    console.initialized = true;

    console_clear();
}

/*
 * Clear the screen
 */
void console_clear(void) {
    if (!console.initialized) return;

    fb_fill_rect(0, 0, console.width, console.height, console.bg_color);
    console.cursor_x = 0;
    console.cursor_y = 0;
}

/*
 * Set colors
 */
void console_set_color(uint32_t fg, uint32_t bg) {
    console.fg_color = fg;
    console.bg_color = bg;
}

/*
 * Print a single character
 */
void console_putchar(char c) {
    if (!console.initialized) return;

    if (c == '\n') {
        console.cursor_x = 0;
        console.cursor_y++;
    } else if (c == '\r') {
        console.cursor_x = 0;
    } else if (c == '\t') {
        console.cursor_x = (console.cursor_x + 8) & ~7;
    } else if (c == '\b') {
        if (console.cursor_x > 0) {
            console.cursor_x--;
        }
    } else if (c >= 32 && c < 127) {
        draw_char(console.cursor_x * CHAR_WIDTH, console.cursor_y * CHAR_HEIGHT,
                  c, console.fg_color, console.bg_color);
        console.cursor_x++;
    }

    /* Handle line wrap */
    if (console.cursor_x >= console.cols) {
        console.cursor_x = 0;
        console.cursor_y++;
    }

    /* Handle scroll */
    if (console.cursor_y >= console.rows) {
        console_scroll();
        console.cursor_y = console.rows - 1;
    }
}

/*
 * Print a string
 */
void console_puts(const char *str) {
    while (*str) {
        console_putchar(*str++);
    }
}

/*
 * Print a string with newline
 */
void console_println(const char *str) {
    console_puts(str);
    console_putchar('\n');
}

/*
 * Print a hex number
 */
void console_print_hex(uint64_t val) {
    console_puts("0x");
    char buf[17];
    char *hex = "0123456789ABCDEF";
    int i;

    for (i = 15; i >= 0; i--) {
        buf[i] = hex[val & 0xF];
        val >>= 4;
    }
    buf[16] = 0;

    /* Skip leading zeros */
    char *p = buf;
    while (*p == '0' && p[1] != '\0') p++;
    console_puts(p);
}

/*
 * Print a decimal number
 */
void console_print_dec(uint64_t val) {
    if (val == 0) {
        console_putchar('0');
        return;
    }

    char buf[21];
    int i = 20;
    buf[i] = '\0';

    while (val > 0 && i > 0) {
        buf[--i] = '0' + (val % 10);
        val /= 10;
    }

    console_puts(&buf[i]);
}

/*
 * Get console dimensions
 */
void console_get_size(uint32_t *cols, uint32_t *rows) {
    *cols = console.cols;
    *rows = console.rows;
}

